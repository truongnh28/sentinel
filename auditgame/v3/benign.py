@dataclass(frozen=True)
class Event:
    wf_id: str
    repo: str
    delta: int
    iota: int
    sigma: int
    payload: Item
    shift: float
    controls: tuple                     # (Change, ...), PER_EVENT of them

    def rows(self) -> tuple:
        pos = features(self.payload, self.sigma, self.shift)
        neg = [features(c.item, c.item.created_at + self.delta, c.shift)
               for c in self.controls]
        return pos, neg


def candidates(runs: DevRuns, delta: int) -> list:
    """Every feasible sleeper placement on CARRIER at `delta`, over dev, pinned order."""
    out = []
    for wf in runs.workflows:
        for sp in P.plan_sleeper_all(wf, CARRIER, delta, EPSILON):
            out.append((wf, sp))
    return out


def build(runs: DevRuns | None = None, kind: str = "drift", n_events: int = N_EVENTS,
          dropped: list | None = None) -> list:
    """N_EVENTS events, spread round-robin over DELTAS, each with PER_EVENT distinct
    controls of `kind` from the same repo; no control is used twice in the corpus.

    Source 1 (v2's rule): the change of the host workflow written at iota = sigma - Delta,
    the one with the payload's age.  Source 2 (v2's harvest top-up): other changes of the
    same repo on dev, re-read at age Delta.  An event that cannot get PER_EVENT controls
    is dropped with a reason (N3)."""
    if kind not in CONTROL_KINDS:
        raise ValueError(f"kind {kind!r} is not one of {CONTROL_KINDS}")
    runs = dev_runs() if runs is None else runs
    sink = dropped if dropped is not None else []
    queues = {}
    for d in DELTAS:
        cand = candidates(runs, d)
        random.Random(seed_of(SEED, "v3-benign", "events", d)).shuffle(cand)
        queues[d] = collections.deque(cand)
    quota = {d: n_events // len(DELTAS) + (i < n_events % len(DELTAS))
             for i, d in enumerate(DELTAS)}
    used, events = set(), []
    got = {d: 0 for d in DELTAS}
    while any(got[d] < quota[d] and queues[d] for d in DELTAS):
        for d in DELTAS:
            if got[d] >= quota[d] or not queues[d]:
                continue
            wf, sp = queues[d].popleft()
            ev = _match(runs, kind, wf, sp, used)
            if ev is None:
                sink.append((wf.wf_id, d, sp.iota, "fewer than PER_EVENT unused controls"))
                continue
            used.update(c.item.content for c in ev.controls)
            events.append(ev)
            got[d] += 1
    for d in DELTAS:
        if got[d] < quota[d]:
            sink.append((None, d, None, f"supply: {got[d]} of {quota[d]} events"))
    return events


def _match(runs: DevRuns, kind: str, wf, sp, used: set):
    payload = sp.item(wf)
    shift = embedding_shift(_before(runs.nominal[wf.wf_id], CARRIER, sp.iota), payload)
    controls = []
    own = runs.at.get((kind, wf.wf_id, sp.iota))
    if own is not None and own.item.content not in used:
        controls.append(own)
    spare = [c for c in runs.pools.get((kind, wf.repo), [])
             if c.item.content not in used and c is not own]
    # distinct contents only (two passes of corpus_v2 share instances)
    seen = {c.item.content for c in controls}
    uniq = []
    for c in spare:
        if c.item.content not in seen:
            seen.add(c.item.content)
            uniq.append(c)
    need = PER_EVENT - len(controls)
    if len(uniq) < need:
        return None
    rng = random.Random(seed_of(SEED, "v3-benign", "ctrl", wf.wf_id, sp.iota, sp.delta))
    controls += rng.sample(uniq, need)
    return Event(wf.wf_id, wf.repo, sp.delta, sp.iota, sp.sigma, payload, shift,
                 tuple(controls))


def rows_of(events: list) -> tuple:
    pos, neg = [], []
    for ev in events:
        p, n = ev.rows()
        pos.append(p)
        neg.extend(n)
    return pos, neg


def v2_rows_of(events: list) -> tuple:
    """v2's F_match (core.Item.surface) on the same items, read at the same `now`."""
    pos = [ev.payload.surface(now=ev.sigma) for ev in events]
    neg = [c.item.surface(now=c.item.created_at + ev.delta)
           for ev in events for c in ev.controls]
    return pos, neg


def corpus_digest(events: list) -> str:
    """sha256 over the canonical (payload, controls) record of every event, in order."""
    rec = [dict(wf=ev.wf_id, delta=ev.delta, iota=ev.iota, sigma=ev.sigma,
                payload=ev.payload.item_id,
                controls=[(c.wf_id, c.t, c.item.item_id) for c in ev.controls],
                rows=ev.rows()) for ev in events]
    return hashlib.sha256(json.dumps(rec, sort_keys=True).encode()).hexdigest()


# ---------------------------------------------------------------------------------------
# The discriminator: v2's algorithm over a declared column set
# ---------------------------------------------------------------------------------------
# discriminator._fit sizes its weights by its module-level _COLS (v2's five features), so
# it cannot score four.  This is the same algorithm (standardise over the whole sample,
# shuffle by the split seed, fit 600 steps at lr 0.3 on the first 60%, AUC and
# Hanley-McNeil on the rest) with the columns as an argument; with cols = v2's F_match it
# reproduces discriminator.auc_with_ci exactly (tested).

def _fit(X: list, y: list, ncol: int, steps: int = 600, lr: float = 0.3) -> tuple:
    w, b = [0.0] * ncol, 0.0
    for _ in range(steps):
        gw, gb = [0.0] * ncol, 0.0
        for xi, yi in zip(X, y):
            z = sum(wj * v for wj, v in zip(w, xi)) + b
            e = 1.0 / (1.0 + math.exp(-max(-30.0, min(30.0, z)))) - yi
            for j in range(ncol):
                gw[j] += e * xi[j]
            gb += e
        n = len(X)
        w = [wj - lr * g / n for wj, g in zip(w, gw)]
        b -= lr * gb / n
    return w, b


def auc_with_ci(pos: list, neg: list, cols, seed: int,
                test_fraction: float = TEST_FRACTION) -> tuple:
    """(auc, lo, hi, weights) of one declared split."""
    cols = tuple(cols)
    rows = [[float(f[c]) for c in cols] for f in pos + neg]
    y = [1.0] * len(pos) + [0.0] * len(neg)
    X = DSC._standardise(rows)
    idx = list(range(len(X)))
    random.Random(seed).shuffle(idx)
    cut = int(len(idx) * (1.0 - test_fraction))
    tr, te = idx[:cut], idx[cut:]
    w, b = _fit([X[i] for i in tr], [y[i] for i in tr], len(cols))
    sc = [sum(wj * v for wj, v in zip(w, X[i])) + b for i in te]
    lab = [y[i] for i in te]
    a = DSC._auc(sc, lab)
    n_pos = int(sum(lab))
    lo, hi = DSC._hanley_mcneil(a, n_pos, len(lab) - n_pos)
    return a, lo, hi, tuple(w)


def over_splits(pos: list, neg: list, cols, seeds=SPLIT_SEEDS) -> dict:
    per = {s: auc_with_ci(pos, neg, cols, s) for s in seeds}
    out = DSC.summarise_splits({s: v[:3] for s, v in per.items()}, CEILING)
    out["lo_mean"] = statistics.fmean(v[1] for v in per.values())
    out["per_seed"] = {s: tuple(round(x, 4) for x in v[:3]) for s, v in per.items()}
    out["weights_mean"] = {c: round(statistics.fmean(v[3][j] for v in per.values()), 4)
                           for j, c in enumerate(cols)}
    return out


def verdict(summary: dict) -> str:
    """The criterion gate2_v2 pins: mean CI95 upper bound over the split seeds <= 0.56."""
    return PASS if summary["hi_mean"] <= CEILING else FAIL


def floor_hi(n_pos: int, n_neg: int, test_fraction: float = TEST_FRACTION) -> float:
    """The CI95 upper bound a test fold of this corpus gives when the AUC is exactly 0.5:
    the lowest mean upper bound the criterion can see on this sample size."""
    fp, fn = round(n_pos * test_fraction), round(n_neg * test_fraction)
    return DSC._hanley_mcneil(0.5, fp, fn)[1]


