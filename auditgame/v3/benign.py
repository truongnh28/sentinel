def mann_whitney(pos: list, neg: list) -> float:
    return DSC._auc(pos + neg, [1] * len(pos) + [0] * len(neg))


def feature_table(pos: list, neg: list, cols) -> dict:
    out = {}
    for c in cols:
        a, b = [float(r[c]) for r in pos], [float(r[c]) for r in neg]
        sa, sb = statistics.pstdev(a), statistics.pstdev(b)
        pooled = math.sqrt((sa * sa + sb * sb) / 2) or 1.0
        auc = mann_whitney(a, b)
        out[c] = dict(auc_single=round(auc, 4), auc_single_folded=round(max(auc, 1 - auc), 4),
                      mean_pos=round(statistics.fmean(a), 4),
                      mean_neg=round(statistics.fmean(b), 4),
                      sd_pos=round(sa, 4), sd_neg=round(sb, 4),
                      smd=round((statistics.fmean(a) - statistics.fmean(b)) / pooled, 4),
                      distinct_pos=len(set(a)), distinct_neg=len(set(b)))
    return out


def _brief(s: dict) -> dict:
    return {k: (round(v, 4) if isinstance(v, float) else v)
            for k, v in s.items() if k != "per_seed"}


def measure(events: list, drop_one: bool = True, per_delta: bool = True) -> dict:
    """Everything the manifest records about one corpus."""
    pos, neg = rows_of(events)
    main = over_splits(pos, neg, FEATURES)
    out = dict(n_events=len(events), n_benign=len(neg), main=main, verdict=verdict(main),
               floor_hi=round(floor_hi(len(pos), len(neg)), 4),
               features=feature_table(pos, neg, FEATURES))
    cf = clustered_floor(events)
    out["floor_hi_clustered"] = cf["floor_hi_clustered"]
    out["clustered"] = cf
    if drop_one:
        out["drop_one"] = {}
        for c in FEATURES:
            s = over_splits(pos, neg, tuple(x for x in FEATURES if x != c))
            out["drop_one"][c] = dict(auc_median=round(s["auc_median"], 4),
                                      hi_mean=round(s["hi_mean"], 4), clear=s["clear"])
    if per_delta:
        out["per_delta"] = {}
        for d in DELTAS:
            sub = [ev for ev in events if ev.delta == d]
            if not sub:
                continue
            p, n = rows_of(sub)
            s = over_splits(p, n, FEATURES)
            out["per_delta"][d] = dict(n_events=len(sub), auc_median=round(s["auc_median"], 4),
                                       hi_mean=round(s["hi_mean"], 4), clear=s["clear"],
                                       floor_hi=round(floor_hi(len(p), len(n)), 4),
                                       verdict=verdict(s))
    return out


