def _tokens(item: Item) -> collections.Counter:
    return collections.Counter(retrieval.as_topic(item.topic))


def _cos(a: collections.Counter, b: collections.Counter) -> float:
    dot = sum(v * b.get(k, 0) for k, v in a.items())
    na = math.sqrt(sum(v * v for v in a.values()))
    nb = math.sqrt(sum(v * v for v in b.values()))
    return dot / (na * nb) if na and nb else 0.0


def embedding_shift(before: list, item: Item) -> float:
    """1 - cos between the carrier's bag of topic tokens before and after `item` is added.
    `before` = the carrier's items written at earlier tasks.  Empty carrier -> 1.0."""
    e0 = collections.Counter()
    for it in before:
        e0.update(_tokens(it))
    if not e0:
        return 1.0
    e1 = e0 + _tokens(item)
    return round(1.0 - _cos(e0, e1), 12)


def provenance_shape(item: Item) -> int:
    return 10 * item.provenance.count("/") + len(item.derived_from)


def features(item: Item, now: int, shift: float) -> dict:
    """The draft's four surface statistics of `item` read at task `now`."""
    return dict(edit_size=len(item.content), embedding_shift=shift,
                recency=now - item.created_at, provenance_shape=provenance_shape(item))


