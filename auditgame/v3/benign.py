def _agent(drift_rates: dict | None = None) -> AG.SleeperMockAgent:
    ag = AG.SleeperMockAgent.for_cell(C.PRIMARY, C.Cell(rho=C.RHO_GRID[0], delta=DELTAS[0]))  # rho, Delta: not read by the agent
    if drift_rates is not None:
        ag.drift_rates = dict(drift_rates)
    return ag


def run_clean(wf, drift_rates: dict | None = None):
    """The v3 agent over `wf` with no payload, seeded as the runner seeds it (rs_of)."""
    from carrier_runner import rs_of
    ag, store = _agent(drift_rates), CarrierStore()
    rs, topics = rs_of(wf, SEED), [t.topic for t in wf.tasks]
    for t, task in enumerate(wf.tasks):
        ag.run_task(t, task, store, seed=rs, marker="x", wf_topics=topics)
    return ag, store


@dataclass(frozen=True)
class Change:
    """One candidate control: an item of CARRIER written at task t of dev workflow wf_id,
    with its embedding shift in the nominal run of that workflow."""
    kind: str
    wf_id: str
    repo: str
    t: int
    item: Item
    shift: float


@dataclass
class DevRuns:
    workflows: list
    nominal: dict = field(default_factory=dict)       # wf_id -> store (nominal drift)
    pools: dict = field(default_factory=dict)         # (kind, repo) -> [Change]
    at: dict = field(default_factory=dict)            # (kind, wf_id, t) -> Change


def _before(store, carrier: str, t: int) -> list:
    return [it for it in store.items[carrier] if it.created_at < t]


def dev_runs(workflows=None) -> DevRuns:
    """Nominal run and forced-drift run of every dev workflow; the per-repo pools."""
    wfs = K.dev_workflows() if workflows is None else list(workflows)
    out = DevRuns(workflows=wfs)
    forced = {c: 0.0 for c in AG.DRIFT_RATES}
    forced[CARRIER] = 1.0
    for wf in wfs:
        _, nominal = run_clean(wf)
        _, gen = run_clean(wf, forced)
        out.nominal[wf.wf_id] = nominal
        for kind, src, prov in (("drift", gen, AG.INGRESS_PROVENANCE),
                                ("v2-notes", nominal, "agent/notes")):
            for it in src.items[CARRIER]:
                if it.provenance != prov or it.poisoned:
                    continue
                ch = Change(kind, wf.wf_id, wf.repo, it.created_at, it,
                            embedding_shift(_before(nominal, CARRIER, it.created_at), it))
                out.pools.setdefault((kind, wf.repo), []).append(ch)
                out.at[(kind, wf.wf_id, it.created_at)] = ch
    return out


