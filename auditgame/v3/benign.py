def salt_family(runs: DevRuns | None = None, salts=G2.SALT_FAMILY) -> dict:
    """The main check under each salt of v2's pre-registered family: the payload's topic
    subset (retrieval.SUBSET_SALT) moves the placements and the payload's tokens.  v2's
    outer rule is >= 14 of 17 salts passing; reported, never used to overturn the main
    verdict in either direction."""
    from unittest import mock
    runs = dev_runs() if runs is None else runs
    out = {}
    for salt in salts:
        with mock.patch.object(retrieval, "SUBSET_SALT", salt):
            ev = build(runs)
            pos, neg = rows_of(ev)
            s = over_splits(pos, neg, FEATURES)
        out[salt] = dict(n_events=len(ev), auc_median=round(s["auc_median"], 4),
                         hi_mean=round(s["hi_mean"], 4), clear=s["clear"], verdict=verdict(s))
    n_pass = sum(1 for v in out.values() if v["verdict"] == PASS)
    return dict(per_salt=out, passing=n_pass, total=len(out),
                rule=G2.SALT_CRITERION["rule"], required=G2.SALT_CRITERION["passing"],
                verdict=PASS if n_pass >= G2.SALT_CRITERION["passing"] else FAIL)
